/**
 * Defines and validates the Arkos configuration, filling in defaults where needed.
 * Use this in your `arkos.config.ts` to get full type safety and autocompletion.
 *
 * @example
 * ```ts
 * // arkos.config.ts
 * import { defineConfig } from "arkos/config";
 *
 * export default defineConfig({
 *   globalPrefix: "/api",
 * });
 * ```
 *
 * @see {@link https://www.arkosjs.com/docs/reference/define-config}
 */
export function defineConfig<const T extends ArkosConfig>(
  config: T,
): ResolveArkosConfig<T> {
  // if (!config.prisma?.instance) {
  //   throw new Error(
  //     "ArkosConfigError: prisma.instance is required. Pass your PrismaClient instance via defineConfig({ prisma: { instance: new PrismaClient() } })."
  //   );
  // }

  // if (!(config.prisma.instance instanceof PrismaClient)) {
  //   throw new Error(
  //     "ArkosConfigError: prisma.instance must be a valid PrismaClient instance."
  //   );
  // }

  const finalConfig: Partial<ArkosConfig> = {
    welcomeMessage:
      "Welcome to our RESTful API generated by Arkos, find out more about Arkos at www.arkosjs.com",
    globalPrefix: "/api",
    ...config,
    source: {
      entryPoint: `src/app.${getUserFileExtension()}`,
      ...config.source,
    },
    port:
      config.port ||
      Number(process.env.__PORT || process.env.CLI_PORT || process.env.PORT) ||
      8000,
    host:
      config.host ||
      process.env.__HOST ||
      process.env.CLI_HOST ||
      process.env.HOST ||
      (process.env.ARKOS_BUILD !== "true" ? "0.0.0.0" : "127.0.0.1"),
    request: {
      ...config.request,
      parameters: {
        allowDangerousPrismaQueryOptions:
          config.request?.parameters?.allowDangerousPrismaQueryOptions ?? false,
        ...config.request?.parameters,
      },
    },
    fileUpload: {
      baseUploadDir: "uploads",
      baseRoute: "/api/uploads",
      serving: "all",
      ...config.fileUpload,
    },
    routers: {
      strict: config.routers?.strict || false,
      ...config.routers,
    },
    middlewares: {
      ...config.middlewares,
    },
    swagger: {
      ...config?.swagger,
      mode: config?.swagger?.mode || config?.validation?.resolver || "prisma",
      enableAfterBuild: config?.swagger?.enableAfterBuild !== false,
      authenticate:
        typeof config?.swagger?.authenticate === "boolean"
          ? config?.swagger?.authenticate
          : config?.swagger?.enableAfterBuild !== false
            ? process.env.ARKOS_BUILD === "true"
            : false,
    },
    debugging: {
      requests: {
        level: config.debugging?.requests?.level || 1,
        ...config.debugging?.requests,
      },
      dynamicLoader: {
        level: config.debugging?.dynamicLoader?.level || 0,
        ...config.debugging?.dynamicLoader,
      },
    },
  };

  (finalConfig as any).__loader = "defineConfig";

  return finalConfig as unknown as ResolveArkosConfig<T>;
}

/**
 * The literal defaults `defineConfig` fills in for omitted options.
 *
 * Defaults that are runtime/environment dependent (`port`, `host`,
 * `source.entryPoint`, `swagger.mode`, `swagger.authenticate`) stay broad; the
 * rest are pinned to their exact literal so the generated `RuntimeArkosConfig`
 * exposes them as-is.
 */
export type UserArkosConfigDefaults = {
  welcomeMessage: "Welcome to our RESTful API generated by Arkos, find out more about Arkos at www.arkosjs.com";
  globalPrefix: "/api";
  port: number;
  host: string;
  source: { entryPoint: string };
  request: { parameters: { allowDangerousPrismaQueryOptions: false } };
  fileUpload: {
    baseUploadDir: "uploads";
    baseRoute: "/api/uploads";
    serving: "all";
  };
  routers: { strict: false };
  swagger: {
    mode: NonNullable<ArkosConfig["swagger"]>["mode"];
    enableAfterBuild: true;
    authenticate: boolean;
  };
  debugging: { requests: { level: 1 }; dynamicLoader: { level: 0 } };
};

/**
 * Overlays the declared config on top of the literal defaults: a declared value
 * always wins, otherwise the default applies. Shared nested objects are merged
 * so both the user's keys and the unwritten defaulted keys are present.
 */
type ResolveArkosConfig<T> = DeepOverride<UserArkosConfigDefaults, T> & {
  __loader: "defineConfig";
};

type DeepOverride<D, T> = T extends readonly unknown[]
  ? T
  : T extends object
    ? D extends object
      ? {
          readonly [K in keyof T | keyof D]: K extends keyof T
            ? K extends keyof D
              ? DeepOverride<D[K], T[K]>
              : T[K]
            : K extends keyof D
              ? D[K]
              : never;
        }
      : T
    : T;

export type UserArkosConfig = Partial<ArkosConfig> & {
  __loader: "defineConfig";
};
